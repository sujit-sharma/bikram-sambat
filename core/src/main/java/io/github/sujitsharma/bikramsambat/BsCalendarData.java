    private BsCalendarData() {
    }

    static void validateYear(int year) {
        if (year < MIN_YEAR || year > MAX_YEAR) {
            throw new BsDateException(
                    "Year " + year + " is out of supported range [" + MIN_YEAR + ", " + MAX_YEAR + "]");
        }
    }

    static int[] monthLengths(int year) {
        validateYear(year);
        return MONTH_LENGTHS[year - MIN_YEAR];
    }

    static int lengthOfMonth(int year, int month) {
        if (month < 1 || month > 12) {
            throw new BsDateException("Invalid BS month value: " + month + " (expected 1-12)");
        }
        return monthLengths(year)[month - 1];
    }

    static int lengthOfYear(int year) {
        int total = 0;
        for (int len : monthLengths(year)) {
            total += len;
        }
        return total;
    }
